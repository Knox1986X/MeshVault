import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import com.meshvault.app.crypto.PasswordGenerator
import com.meshvault.app.crypto.PasswordOptions
import kotlin.math.roundToInt

@Composable
fun GeneratorScreen() {
    val context = LocalContext.current
    var isPassphrase by remember { mutableStateOf(false) }

    var length by remember { mutableIntStateOf(18) }
    var useUpper by remember { mutableStateOf(true) }
    var useLower by remember { mutableStateOf(true) }
    var useDigits by remember { mutableStateOf(true) }
    var useSymbols by remember { mutableStateOf(true) }
    var avoidAmbiguous by remember { mutableStateOf(false) }

    var wordCount by remember { mutableIntStateOf(5) }
    var capitalizeWords by remember { mutableStateOf(true) }

    fun generateCurrent(): String {
        return if (isPassphrase) {
            PasswordGenerator.generatePassphrase(wordCount = wordCount, capitalize = capitalizeWords)
        } else {
            PasswordGenerator.generatePassword(
                PasswordOptions(
                    length = length,
                    includeUppercase = useUpper,
                    includeLowercase = useLower,
                    includeDigits = useDigits,
                    includeSymbols = useSymbols,
                    avoidAmbiguous = avoidAmbiguous
                )
            )
        }
    }

    var generated by remember { mutableStateOf(generateCurrent()) }

    fun regenerate() {
        generated = generateCurrent()
    }

    fun copy() {
        val cm = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
        cm.setPrimaryClip(ClipData.newPlainText("Generated Password", generated))
        Toast.makeText(context, "Пароль скопирован", Toast.LENGTH_SHORT).show()
    }

    val strength = PasswordGenerator.evaluateStrength(generated)

    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(16.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp)
    ) {
        SingleChoiceSegmentedButtonRow(modifier = Modifier.fillMaxWidth()) {
            SegmentedButton(
                selected = !isPassphrase,
                onClick = {
                    isPassphrase = false
                    regenerate()
                },
                shape = SegmentedButtonDefaults.itemShape(0, 2)
            ) {
                Text("Пароль")
            }
            SegmentedButton(
                selected = isPassphrase,
                onClick = {
                    isPassphrase = true
                    regenerate()
                },
                shape = SegmentedButtonDefaults.itemShape(1, 2)
            ) {
                Text("Парольная фраза")
            }
        }

        Card(
            shape = RoundedCornerShape(16.dp),
            colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant)
        ) {
            Column(modifier = Modifier.padding(16.dp)) {
                Row(
                    verticalAlignment = Alignment.CenterVertically,
                    modifier = Modifier.fillMaxWidth()
                ) {
                    Text(
                        text = generated,
                        style = MaterialTheme.typography.titleLarge,
                        fontFamily = FontFamily.Monospace,
                        fontWeight = FontWeight.Medium,
                        modifier = Modifier.weight(1f)
                    )
                    IconButton(onClick = { regenerate() }) {
                        Icon(Icons.Default.Refresh, contentDescription = "Обновить")
                    }
                    IconButton(onClick = { copy() }) {
                        Icon(Icons.Default.ContentCopy, contentDescription = "Копировать")
                    }
                }
                Spacer(modifier = Modifier.height(10.dp))
                LinearProgressIndicator(
                    progress = { strength.score },
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(6.dp)
                )
                Spacer(modifier = Modifier.height(6.dp))
                Text(
                    text = "Надёжность: ${strength.label}",
                    style = MaterialTheme.typography.labelMedium,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
        }

        if (!isPassphrase) {
            Column {
                Text("Длина: $length", style = MaterialTheme.typography.titleSmall)
                Slider(
                    value = length.toFloat(),
                    onValueChange = {
                        length = it.roundToInt()
                        regenerate()
                    },
                    valueRange = 8f..48f
                )
            }
            OptionSwitch("Заглавные (A-Z)", useUpper) { useUpper = it; regenerate() }
            OptionSwitch("Строчные (a-z)", useLower) { useLower = it; regenerate() }
            OptionSwitch("Цифры (0-9)", useDigits) { useDigits = it; regenerate() }
            OptionSwitch("Символы (!@#...)", useSymbols) { useSymbols = it; regenerate() }
            OptionSwitch("Исключить похожие (0, O, l, 1)", avoidAmbiguous) { avoidAmbiguous = it; regenerate() }
        } else {
            Column {
                Text("Количество слов: $wordCount", style = MaterialTheme.typography.titleSmall)
                Slider(
                    value = wordCount.toFloat(),
                    onValueChange = {
                        wordCount = it.roundToInt()
                        regenerate()
                    },
                    valueRange = 3f..10f
                )
            }
            OptionSwitch("Заглавная буква в каждом слове", capitalizeWords) {
                capitalizeWords = it
                regenerate()
            }
        }
    }
}

@Composable
private fun OptionSwitch(
    label: String,
    checked: Boolean,
    onCheckedChange: (Boolean) -> Unit
) {
    Row(
        modifier = Modifier.fillMaxWidth(),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.SpaceBetween
    ) {
        Text(text = label, style = MaterialTheme.typography.bodyLarge)
        Switch(checked = checked, onCheckedChange = onCheckedChange)
    }
}
